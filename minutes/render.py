"""Write the transcript (.txt, .srt, plain) and the minutes (.md, .json)."""
from pathlib import Path

from .audio import fmt_ts
from .summarize import Minutes
from .transcribe import Segment


def write_transcripts(segments: list[Segment], base: Path) -> list[Path]:
    txt = base.with_name(base.name + "_transcript.txt")
    srt = base.with_name(base.name + "_transcript.srt")
    plain = base.with_name(base.name + "_plain.txt")
    txt.write_text("".join(f"[{fmt_ts(s.start)} - {fmt_ts(s.end)}] {s.text}\n" for s in segments), encoding="utf-8")
    srt.write_text(
        "".join(
            f"{i}\n{fmt_ts(s.start, True)} --> {fmt_ts(s.end, True)}\n{s.text}\n\n" for i, s in enumerate(segments, 1)
        ),
        encoding="utf-8",
    )
    plain.write_text(" ".join(s.text for s in segments if s.text) + "\n", encoding="utf-8")
    return [txt, srt, plain]


def _ts(item) -> str:
    return f" `[{item.timestamp}]`" if item.timestamp else ""


def minutes_markdown(m: Minutes, source: str) -> str:
    out = [f"# {m.title}", "", f"_Source: {source}_", ""]
    if m.participants:
        out += [f"**Participants:** {', '.join(m.participants)}", ""]
    out += ["## Summary", "", m.summary or "_No summary._", ""]

    def section(title: str, items) -> None:
        if items:
            out.extend([f"## {title}", ""] + [f"- {i.text}{_ts(i)}" for i in items] + [""])

    section("Key points", m.key_points)
    section("Decisions", m.decisions)
    if m.action_items:
        out += ["## Action items", "", "| Task | Owner | Due | When |", "|---|---|---|---|"]
        for a in m.action_items:
            out.append(f"| {a.text} | {a.owner or '_unassigned_'} | {a.due or '-'} | {a.timestamp or '-'} |")
        out.append("")
    section("Open questions", m.open_questions)
    out.append("_Generated by meeting-minutes-ai. Check important details against the transcript._")
    return "\n".join(out) + "\n"


def write_minutes(m: Minutes, base: Path, source: str) -> list[Path]:
    md = base.with_name(base.name + "_minutes.md")
    js = base.with_name(base.name + "_minutes.json")
    md.write_text(minutes_markdown(m, source), encoding="utf-8")
    js.write_text(m.model_dump_json(indent=2), encoding="utf-8")
    return [md, js]
